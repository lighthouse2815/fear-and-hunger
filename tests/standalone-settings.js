'use strict';
const assert = require('node:assert/strict');
const { PlayerSettings } = require('../game/engine/player-settings');
const values = new Map(), storage = { getItem: key => values.get(key) || null, setItem: (key,value) => values.set(key,value) };
const settings = new PlayerSettings({storage,key:'settings'});
assert.equal(settings.volumes.master,5);assert.equal(settings.volumes.bgm,100);
assert.equal(settings.actionFor('T'),'torch');assert.equal(settings.actionFor('c'),'skill');assert.equal(settings.actionFor('ArrowRight'),'right');
settings.setVolume('master',3);settings.setVolume('bgm',37);settings.setVolume('se',-20);settings.setVolume('bgs',200);
assert.equal(settings.volumes.se,0);assert.equal(settings.volumes.bgs,100);
settings.bind('H','torch');settings.bind('t','');settings.alwaysDash=false;settings.save();
const restored = new PlayerSettings({storage,key:'settings'});
assert.equal(restored.volumes.master,3);assert.equal(restored.volumes.bgm,37);
assert.equal(restored.actionFor('h'),'torch');assert.equal(restored.actionFor('t'),'');assert.equal(restored.alwaysDash,false);
restored.layout(true);assert.equal(restored.actionFor('w'),'up');assert.equal(restored.actionFor('d'),'right');assert.equal(restored.actionFor('ArrowUp'),'up');
restored.layout(false);assert.equal(restored.actionFor('w'),'pagedown');assert.equal(restored.actionFor('t'),'torch');assert.equal(restored.actionFor('h'),'');
assert.equal(restored.volumes.master,3,'đặt lại phím không đổi âm lượng');
restored.setVolume('master',100);assert.equal(restored.volumes.master,5,'không tăng tổng vượt 5%');
storage.setItem('loud',JSON.stringify({version:1,volumes:{master:100,bgm:73},keys:{h:'torch'},alwaysDash:false}));
const quiet=new PlayerSettings({storage,key:'loud'});
assert.equal(quiet.volumes.master,5,'cấu hình đã lưu không vượt giới hạn');assert.equal(quiet.volumes.bgm,73);
assert.equal(quiet.actionFor('h'),'torch');assert.equal(quiet.alwaysDash,false);
quiet.setVolume('master',0);assert.equal(quiet.volumes.master,0);quiet.setVolume('master',2);assert.equal(quiet.volumes.master,2);
assert.throws(()=>restored.bind('F5','ok'),/không hợp lệ/);assert.throws(()=>restored.bind('a','script'),/không hợp lệ/);
assert.throws(()=>restored.bind('__proto__','ok'),/không hợp lệ/);assert.throws(()=>restored.setVolume('unknown',3),/không hợp lệ/);
assert.throws(()=>restored.setVolume('master',NaN),/không hợp lệ/);
storage.setItem('bad','{');assert.equal(new PlayerSettings({storage,key:'bad'}).volumes.master,5);
storage.setItem('bad',JSON.stringify({version:1,volumes:{master:'100',bgm:500,se:-30},keys:{t:'script',ArrowDown:'up','__proto__':'ok'},alwaysDash:'false'}));
const invalid=new PlayerSettings({storage,key:'bad'});
assert.equal(invalid.volumes.master,5);assert.equal(invalid.volumes.bgm,100);assert.equal(invalid.volumes.se,0);
assert.equal(invalid.actionFor('t'),'torch');assert.equal(invalid.actionFor('ArrowDown'),'up');assert.equal(invalid.alwaysDash,true);
const blocked=new PlayerSettings({storage:{getItem(){throw new Error('bị chặn');},setItem(){throw new Error('hết chỗ');}}});
assert.equal(blocked.volumes.master,5);assert.throws(()=>blocked.setVolume('master',100),/hết chỗ/);assert.equal(blocked.volumes.master,5);
assert.throws(()=>blocked.bind('h','torch'),/hết chỗ/);assert.equal(blocked.actionFor('h'),'');
assert.throws(()=>blocked.layout(true),/hết chỗ/);assert.equal(blocked.actionFor('w'),'pagedown');
console.log('ĐẠT: tùy chọn mặc định 5%, nhóm âm lượng, lưu/đọc, đổi/xóa phím, WASD/reset, dữ liệu hỏng và lỗi storage.');

'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const FNH = { Scene: class {} };
for (const file of ['interpreter', 'scene_map', 'game']) {
    vm.runInNewContext(fs.readFileSync(path.join(__dirname, '../fnh-engine/js/' + file + '.js'), 'utf8'), { window: { FNH } });
}
const scene = new FNH.Scene_Map();
let over = 0, title = 0, saved = 0;
scene.game = { flags: {}, gold: 0, player: { hp: 10 }, data: {},
    audio: { playSe() {} }, getSaveInfo: () => null, gameOver() { over += 1; }, returnToTitle() { title += 1; },
    storage: { save() { saved += 1; return true; } } };
scene.input = { isPressed: () => false };
scene.map = { events: [] };
const command = (code, parameters = []) => ({ code, parameters });
const execute = (code, parameters) => scene.executeEventCommand(command(code, parameters));
execute(134, [0]);
assert.equal(scene.pauseEntries().find((entry) => entry.id === 'save').enabled, false);
assert.equal(FNH.Game.prototype.saveGame.call(scene.game), false);
assert.equal(saved, 0);
execute(134, [1]);
assert.equal(FNH.Game.prototype.saveGame.call(scene.game), true);
execute(211, [0]);
assert.equal(scene.game.player.transparent, true);
execute(211, [1]);
assert.equal(scene.game.player.transparent, false);
scene.startEventList({ list: [command(351), command(125, [0, 0, 5])] }, 0);
assert.equal(scene.eventRunner.wait.type, 'pause');
assert.equal(scene.paused, true);
scene.updateEvent(0);
assert.equal(scene.game.gold, 0);
scene.closePause();
scene.updateEvent(0);
assert.equal(scene.game.gold, 5);
assert.equal(scene.eventRunner, null);
scene.startEventList({ list: [command(353), command(125, [0, 0, 100])] }, 0);
assert.equal(over, 1);
assert.equal(scene.game.gold, 5, 'Không chạy hậu quả sau chuyển game over');
scene.leaving = false;
scene.startEventList({ list: [command(354), command(125, [0, 0, 100])] }, 0);
assert.equal(title, 1);
assert.equal(scene.game.gold, 5);
scene.leaving = false;
scene.ready = true;
scene.updateMoveRoutes = () => {};
scene.updateParallelEvents = () => {};
scene.updateMovement = () => {};
scene.updateCamera = () => {};
scene.updateEventImages = () => {};
scene.input = { isPressed: (key) => key === 'Escape' };
execute(135, [0]);
scene.update(0);
assert.equal(scene.paused, false, 'Khóa menu chặn phím mở menu');
execute(135, [1]);
scene.update(0);
assert.equal(scene.paused, true);
scene.closePause();
scene.game.player.hp = 0;
scene.update(0);
assert.equal(over, 2, 'Nhân vật hết HP chuyển game over sau event');
console.log('ĐẠT: khóa lưu/menu, ẩn người chơi, chờ menu, game over và về tiêu đề.');

scene.leaving = false;
scene.game.player.hp = 10;
execute(124, [0, 30]);
assert.equal(scene.eventCondition([3, 30, 0]), true);
assert.equal(scene.eventCondition([3, 29, 1]), false);
assert.equal(scene.eventDataOperand(7, 3, 0), 30);
execute(124, [1]);
assert.equal(scene.eventCondition([3, 30, 0]), false);
assert.equal(scene.eventDataOperand(7, 3, 0), 30, 'Dừng timer giữ giá trị hiện tại');
const game = Object.create(FNH.Game.prototype);
game.sceneName = 'map';
game.scene = { paused: false, update() {} };
game.screenEffects = { update() {} };
game.transition = { update() {} };
game.input = { clearFrame() {} };
game.eventTimer = { seconds: 2, working: true };
game.update(0.5);
assert.equal(game.eventTimer.seconds, 1.5);
game.scene.paused = true;
game.update(1);
assert.equal(game.eventTimer.seconds, 1.5);
game.sceneName = 'battle';
let returned = 0;
game.scene = { update() {}, returnToMap() { returned += 1; } };
game.update(2);
assert.equal(game.eventTimer.seconds, 0);
assert.equal(returned, 1);
game.update(2);
assert.equal(returned, 1, 'Hết giờ không thoát trận nhiều lần');
console.log('ĐẠT: timer đếm ngược, điều kiện/biến, dừng menu và kết thúc trận khi hết giờ.');

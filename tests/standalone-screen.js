'use strict';
const assert = require('node:assert/strict');
const { GameState } = require('../game/engine/game-state');
const { ScreenRuntime } = require('../game/engine/screen-runtime');

(async () => {
    const state = new GameState();
    const runtime = new ScreenRuntime(state), screen = runtime.screen;
    // Thực thi nguyên tham số picture từ mở đầu game, không tự tạo dữ liệu thay thế.
    const opening = require('../game/data/Map010.json').events[1].pages[0].list;
    for (const command of opening.filter(command => command.code === 231)) runtime.handleEffect(command.code, command.parameters);
    assert.equal(screen.pictures[1].name, 'character_select_bg');
    assert.equal(screen.pictures[6].name, 'Actor1_1');
    const fade = opening.find(command => command.code === 232);
    runtime.handleEffect(fade.code, fade.parameters);
    runtime.advance(15);
    assert.equal(screen.pictures[1].opacity, 127.5);
    const snapshot = state.toJSON();
    const restored = new ScreenRuntime(new GameState(snapshot));
    restored.advance(15);
    assert.equal(restored.screen.pictures[1].opacity, 255, 'khôi phục tween picture đang chạy');
    runtime.advance(15);
    let done = false;
    const moved = runtime.handleEffect(232, [1, 0, 1, 0, 400, 300, 50, 50, 80, 0, 20, true]).then(() => { done = true; });
    runtime.advance(10);
    assert.equal(screen.pictures[1].x, 200);
    assert.equal(done, false);
    runtime.advance(10);
    await moved;
    assert.equal(screen.pictures[1].origin, 1);
    assert.equal(screen.pictures[1].scaleX, 50);
    runtime.handleEffect(233, [1, 4]); runtime.advance(5);
    assert.equal(screen.pictures[1].angle, 10);
    const tint = runtime.handleEffect(234, [1, [-255, 0, 0, 255], 10, true]);
    runtime.advance(10); await tint;
    assert.equal(screen.pictures[1].tone.red, -255);
    runtime.handleEffect(232, [1, 0, 0, 0, 0, 0, 100, 100, 255, 0, 60, false]);
    runtime.handleEffect(235, [1]);
    assert.equal(screen.pictures[1], undefined);
    assert.equal(screen.tweens.length, 0);
    state.setVariable(1, 40); state.setVariable(2, 80);
    runtime.handleEffect(231, [1, 'Actor1_1', 0, 1, 1, 2, 100, 100, 255, 0]);
    assert.deepEqual([screen.pictures[1].x, screen.pictures[1].y], [40, 80]);
    const old = runtime.handleEffect(232, [1, 0, 0, 0, 100, 100, 100, 100, 0, 0, 100, true]);
    runtime.handleEffect(231, [1, 'Actor1_3', 0, 0, 0, 0, 100, 100, 255, 0]);
    await old;
    runtime.advance(100);
    assert.equal(screen.pictures[1].opacity, 255, 'show mới hủy move của hình cũ cùng ID');
    const blackout = runtime.handleEffect(221, []);
    runtime.advance(24); await blackout;
    assert.equal(screen.brightness, 0);
    const fadein = runtime.handleEffect(222, []);
    runtime.advance(24); await fadein;
    assert.equal(screen.brightness, 255);
    const screenTint = runtime.handleEffect(223, [[-255, -255, -255, 0], 1, true]);
    runtime.advance(1); await screenTint;
    assert.equal(screen.tone.red, -255);
    runtime.handleEffect(224, [[255, 100, 20, 200], 20, false]);
    runtime.advance(10);
    assert.equal(screen.flash.opacity, 100);
    runtime.advance(10);
    assert.equal(screen.flash.opacity, 0);
    const shake = runtime.handleEffect(225, [5, 5, 20, true]);
    runtime.advance(20); await shake;
    assert.equal(screen.shake.remaining, 0);
    runtime.handleEffect(236, ['snow', 6, 10, false]);
    runtime.advance(5);
    assert.equal(screen.weather.power, 3);
    runtime.handleEffect(236, ['none', 0, 5, false]);
    runtime.advance(5);
    assert.equal(screen.weather.power, 0);
    const waiting = runtime.handleEffect(230, [120]);
    runtime.dispose(); await waiting;
    assert.equal(runtime.handleEffect(999, []), false);
    console.log('ĐẠT: picture mở đầu thật, tween/chờ/thay/xóa, màu/flash/rung/thời tiết và save giữa hiệu ứng.');
})().catch(error => { console.error(error); process.exitCode = 1; });

'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { GameEngine } = require('../game/engine/game-engine');
const { GameDataStore } = require('../game/engine/data-store');
const { EventScheduler } = require('../game/engine/event-scheduler');
const flush = () => new Promise(resolve => setImmediate(resolve));
(async () => {
    const store = new GameDataStore({ fetchImpl: async url => ({ ok: true, json: async () =>
        JSON.parse(fs.readFileSync(path.join(__dirname, '../game', url), 'utf8')) }) });
    const e = new GameEngine({ dataStore: store }); await e.boot();
    assert.equal(e.state.transparent, e.database.System.optTransparent, 'chơi mới đọc cờ ẩn nhân vật trong System');
    assert.deepEqual(e.state.party, e.database.System.partyMembers);
    await e.loadMap(72, { x: 0, y: 0, direction: 2 });
    const errors = [], scheduler = new EventScheduler(e, {}, error => errors.push(error));
    const frames = async count => { for (let i = 0; i < count; i++) { scheduler.tick(); e.advanceRoutes(1); await flush(); } };
    scheduler.tick(); await flush();
    assert.equal(e.eventRunning, true); assert.equal(e.move(6), false);
    await frames(39); assert.equal(e.state.screen.pictures[1], undefined, 'chờ đủ 40 frame mới hiện splash');
    await frames(1);
    const splash = e.state.screen.pictures[1];
    assert.equal(splash.name, 'splash_screen1'); assert.equal(splash.opacity, 0);
    fs.accessSync(path.join(__dirname, '../game/img/pictures', splash.name + '.png'));
    await frames(20); assert.equal(splash.opacity, 127.5, 'fade vào theo dữ liệu 40 frame');
    await frames(20); assert.equal(splash.opacity, 255);
    await frames(99); assert.equal(splash.opacity, 255, 'giữ ảnh 100 frame');
    await frames(21); assert.equal(splash.opacity, 127.5, 'fade ra theo dữ liệu 40 frame');
    await frames(20); assert.equal(splash.opacity, 0); assert.equal(e.state.scene, 'map');
    await frames(40); assert.equal(e.state.scene, 'title'); assert.equal(e.eventRunning, false);
    assert.equal(scheduler.autorun, null); assert.equal(e.screen.screen.tweens.length, 0);
    await frames(300); assert.equal(e.state.scene, 'title'); assert.equal(e.state.screen.pictures[1], splash, 'về title không chạy lại splash');
    assert.equal(e.state.x, 0); assert.equal(e.state.y, 0); assert.deepEqual(errors, []); scheduler.stop();
    const manual = new GameEngine({ dataStore: store });
    await manual.boot({ mapId: 74, x: 8, y: 8, party: [1], transparent: false });
    assert.equal(manual.state.transparent, false, 'preview và save giữ cờ được chỉ định');
    const cancel = new GameEngine({ dataStore: store }); await cancel.boot(); await cancel.loadMap(72, { x: 0, y: 0 });
    const controller = new AbortController(), running = cancel.runEvent(1, {}, controller.signal);
    const rejected = assert.rejects(running, { name: 'AbortError' }); await flush(); controller.abort(); await rejected;
    cancel.advanceRoutes(400); await flush(); assert.equal(cancel.state.scene, 'map');
    assert.equal(cancel.state.screen.pictures[1], undefined); assert.equal(cancel.eventRunning, false);
    console.log('ĐẠT: Map072 thật chờ/fade/giữ ảnh/354 theo frame, khóa autorun, System.optTransparent, không lặp ở title và hủy.');
})().catch(error => { console.error(error); process.exitCode = 1; });

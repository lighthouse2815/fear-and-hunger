'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const FNH = { Scene: class {} };
for (const file of ['pictures', 'interpreter', 'scene_map']) {
    vm.runInNewContext(fs.readFileSync(path.join(__dirname, '../fnh-engine/js/' + file + '.js'), 'utf8'), { window: { FNH } });
}
const assets = { loadImage: () => Promise.resolve({ width: 10, height: 20 }) };
const pictures = new FNH.PictureManager(assets);
const values = { x: 10, y: 20, scaleX: 100, scaleY: 100, opacity: 255 };
pictures.show(1, 'test', 0, values, 0);
pictures.move(1, 1, { x: 110, y: 220, scaleX: 200, scaleY: 50, opacity: 0 }, 1, 60);
pictures.rotate(1, 2);
pictures.tint(1, [-100, 20, 0, 100], 60);
pictures.update(0.5);
assert.equal(pictures.get(1).x, 60);
assert.equal(pictures.get(1).opacity, 127.5);
assert.equal(pictures.get(1).angle, 30);
assert.equal(pictures.get(1).tone[0], -50);
const restored = new FNH.PictureManager(assets, JSON.parse(JSON.stringify(pictures)));
restored.update(0.5);
assert.equal(restored.get(1).x, 110);
assert.equal(restored.get(1).tone[0], -100);
assert.equal(restored.get(1).angle, 60);
pictures.show(1, 'battle', 0, values, 0, 'battle');
pictures.erase(1);
assert.equal(pictures.get(1), undefined);
assert.equal(pictures.get(1, 'battle').name, 'battle');
assert.throws(() => pictures.show(101, 'bad', 0, values, 0), /1–100/);
const scene = new FNH.Scene_Map();
scene.game = { assets, flags: { 'variable:3': 80, 'variable:4': 90 }, gold: 0, player: {}, data: {}, showToast() {} };
scene.map = { events: [] };
scene.input = { isPressed: () => false };
const c = (code, parameters) => ({ code, parameters });
scene.executeEventCommand(c(231, [2, 'test', 1, 1, 3, 4, 100, 100, 255, 0]));
assert.equal(scene.game.pictures.get(2).x, 80);
assert.equal(scene.game.pictures.get(2).y, 90);
scene.startEventList({ list: [c(232, [2, '', 0, 0, 180, 190, 50, 50, 100, 0, 60, true]), c(125, [0, 0, 5])] }, 0);
assert.equal(scene.eventRunner.wait.seconds, 1);
scene.game.pictures.update(0.5);
scene.updateEvent(0.5);
assert.equal(scene.game.gold, 0);
scene.game.pictures.update(0.5);
scene.updateEvent(0.5);
assert.equal(scene.game.gold, 5);
assert.equal(scene.game.pictures.get(2).x, 180);
scene.executeEventCommand(c(233, [2, 4]));
assert.equal(scene.game.pictures.get(2).speed, 4);
assert.equal(scene.executeEventCommand(c(234, [2, [0, 0, 0, 255], 30, true])).seconds, 0.5);
scene.executeEventCommand(c(235, [2]));
assert.equal(scene.game.pictures.get(2), undefined);
// Kiểm tra thứ tự vẽ và khôi phục trạng thái Canvas.
pictures.images.set('battle', { image: { width: 10, height: 20 } });
pictures.show(3, 'battle', 0, values, 0, 'battle');
const drawn = [];
const ctx = { save() {}, restore() {}, translate(x) { drawn.push(x); }, rotate() {}, scale() {}, drawImage() {} };
pictures.get(1, 'battle').x = 1;
pictures.get(3, 'battle').x = 3;
pictures.draw(ctx, 'battle');
assert.deepEqual(drawn, [1, 3]);
console.log('ĐẠT: ảnh sự kiện, nội suy, xoay, tint, phạm vi, thứ tự vẽ, chờ và khôi phục dữ liệu.');

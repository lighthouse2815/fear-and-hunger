'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const FNH = {};
vm.runInNewContext(fs.readFileSync('fnh-engine/js/name_input.js', 'utf8'), { window: { FNH } });
const actor = { name: 'Tên' };
const down = new Set();
const scene = { paused: false, game: { canvas: { focus() {} }, audio: { playSe() {} } },
    input: { down, clearFrame() {}, isPressed: (...keys) => keys.some((key) => down.has(key)) } };
function press(key) { down.add(key); scene.nameInput.update(1 / 60); down.clear(); }
scene.nameInput = new FNH.NameInput(scene, actor, 4);
assert.equal(scene.paused, true);
press('Enter');
assert.equal(scene.nameInput.value, 'TênA');
press('Enter');
assert.equal(scene.nameInput.value, 'TênA', 'Không vượt giới hạn tên');
assert.equal(actor.name, 'Tên', 'Tên đang chỉnh chưa ghi vào actor');
press('Escape'); press('PageDown'); press('Enter');
assert.equal(scene.nameInput.value, 'TênÁ', 'Trang thứ hai nhập ký tự có dấu');
press('Shift'); press('Enter');
assert.equal(actor.name, 'TênÁ');
assert.equal(scene.nameInput, null);
assert.equal(scene.paused, false);
scene.nameInput = new FNH.NameInput(scene, actor, 4);
for (let i = 0; i < 4; i += 1) press('Backspace');
press('Shift'); press('Enter');
assert.equal(scene.nameInput.value, 'TênÁ', 'Tên trống khôi phục mặc định trước khi cho xác nhận');
assert.equal(scene.nameInput.token.done, false);
scene.nameInput.close();
assert.equal(actor.name, 'TênÁ', 'Đóng cửa sổ không ghi tên chưa xác nhận');
console.log('ĐẠT: bảng đặt tên gốc, đổi trang, giới hạn, tên trống và không ghi khi chưa xác nhận.');

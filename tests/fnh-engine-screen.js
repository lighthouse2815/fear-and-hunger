'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const FNH = { Scene: class {}, Scene_Map: class {}, clamp: (v, min, max) => Math.max(min, Math.min(max, v)) };
for (const file of ['screen_effects', 'pictures', 'interpreter', 'scene_map', 'game']) {
    vm.runInNewContext(fs.readFileSync(path.join(__dirname, '../fnh-engine/js/' + file + '.js'), 'utf8'), { window: { FNH } });
}
const c = (code, parameters = []) => ({ code, parameters });
const values = (array) => Array.from(array);
let effects = new FNH.ScreenEffects();
effects.tint([-80, 20, 40, 100], 60);
effects.update(0.5);
assert.deepEqual(values(effects.tone), [-40, 10, 20, 50]);
effects.update(0.5);
assert.deepEqual(values(effects.tone), [-80, 20, 40, 100]);
effects.tint([10, 0, 0, 0], 0);
assert.deepEqual(values(effects.tone), [10, 0, 0, 0]);
effects.fade(0, 24);
effects.update(0.2);
assert.equal(effects.brightness, 127.5);
effects.update(0.2);
assert.equal(effects.brightness, 0);
effects.fade(255, 0);
assert.equal(effects.brightness, 255);
effects.startFlash([255, 100, 50, 200], 60);
effects.update(0.25);
assert.equal(effects.flash[3], 150);
effects.update(1);
assert.equal(effects.flash[3], 0);
effects.shake(5, 4, 60);
effects.update(0.1);
assert.ok(Math.abs(effects.shakeX) > 0);
effects.update(2);
assert.equal(effects.shakeX, 0);


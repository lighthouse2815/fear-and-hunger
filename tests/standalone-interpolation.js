'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { GameEngine } = require('../game/engine/game-engine');
const { GameDataStore } = require('../game/engine/data-store');
const { displayPosition } = require('../game/engine/map-model');
const flush = () => new Promise(resolve => setImmediate(resolve));
(async () => {
    const store = new GameDataStore({ fetchImpl: async url => ({ ok: true, json: async () =>
        JSON.parse(fs.readFileSync(path.join(__dirname, '../game', url), 'utf8')) }) });
    const db = await store.loadDatabase(); db.Tilesets = [null, { flags: [16, 0], tilesetNames: [] }];
    const map = { width: 40, height: 30, tilesetId: 1, data: Array(1200).fill(1).concat(Array(6000).fill(0)), events: [null,
        { id: 1, x: 15, y: 10, pages: [{ conditions: {}, priorityType: 1, trigger: 0, through: false, moveType: 0,
            moveSpeed: 4, moveFrequency: 5, walkAnime: true, image: { characterName: '$guard1', direction: 2, pattern: 1 }, list: [] }] }] };
    const e = new GameEngine({ dataStore: { loadDatabase: async () => db, loadMap: async () => map }, random: () => 0.5, onRouteEffect: () => true });
    await e.boot({ mapId: 1, x: 8, y: 8, party: [1, 3], guests: [2], alwaysDash: false });
    const position = () => displayPosition(e.state), view = () => e.map.viewport(e.state, 816, 624);
    assert.equal(e.move(6), true); assert.equal(e.state.x, 9, 'tọa độ gameplay vào ô đích');
    assert.deepEqual(position(), { x: 8, y: 8, lift: 0 }); assert.equal(e.state.moveFrames, 16);
    e.advanceRoutes(4); assert.equal(position().x, 8.25); assert.equal(view().startX, 0.25);
    e.advanceRoutes(4); assert.equal(position().x, 8.5); assert.equal(view().startX, 0.5);
    const halfway = e.save(); e.advanceRoutes(8); assert.equal(position().x, 9); assert.equal(e.state.motion, undefined);
    await e.restore(halfway); assert.equal(position().x, 8.5); assert.equal(e.state.moveFrames, 8, 'save giữa bước giữ tiến độ');
    assert.equal(e.openMenu(), true); e.advanceRoutes(100); assert.equal(position().x, 8.5, 'menu tạm dừng bước'); e.closeMenu();
    e.battle.setup(1, true, true); e.state.scene = 'battle'; e.advanceRoutes(100);
    assert.equal(position().x, 8.5, 'trận tạm dừng bước map'); e.battle.finish('escape'); e.state.scene = 'map';
    e.advanceRoutes(8); assert.equal(position().x, 9);
    e.state.alwaysDash = true; assert.equal(e.move(2), true); assert.equal(e.state.moveFrames, 8);
    e.advanceRoutes(4); assert.deepEqual(position(), { x: 9, y: 8.5, lift: 0 });
    const follower = e.state.followers()[0]; assert.equal(follower.x, 9); assert.equal(follower.y, 8);
    assert.deepEqual(displayPosition(follower), { x: 8.5, y: 8, lift: 0 }, 'follower đi mượt qua góc rẽ');
    assert.deepEqual(displayPosition(e.state.followers()[1]), { x: 8, y: 8, lift: 0 }, 'guest chờ người phía trước');
    await e.restore(e.save()); assert.equal(displayPosition(e.state.followers()[0]).x, 8.5);
    e.advanceRoutes(4); assert.equal(position().y, 9);
    const blocker = e.map.eventById(1); e.map.locateEvent(1, 10, 9);
    assert.equal(e.move(6), false); assert.equal(e.state.motion, undefined, 'va chạm không tạo trượt hình');
    e.state.through = true; assert.equal(e.move(6), true); e.advanceRoutes(4);
    assert.equal(position().x, 9.5); assert.equal(e.state.x, 10);
    await e.createInterpreter([{ code: 203, parameters: [-1, 0, 2, 2, 8] }], 0).run();
    assert.deepEqual(position(), { x: 2, y: 2, lift: 0 }); assert.equal(e.state.moveFrames, 0, '203 dịch chuyển tức thời');

    e.map.locateEvent(1, 15, 10);
    let route = e.movement.start(blocker, { list: [{ code: 3 }, { code: 0 }] });
    assert.deepEqual(displayPosition(blocker), { x: 15, y: 10, lift: 0 }); assert.equal(blocker.x, 16);
    e.advanceRoutes(8); assert.equal(displayPosition(blocker).x, 15.5);
    await e.createInterpreter([{ code: 122, parameters: [7300, 7300, 0, 3, 5, 1, 3] }], 0).run();
    assert.equal(e.state.variableValue(7300), 768, 'Screen X đọc vị trí hiển thị giữa bước');
    const npcSave = e.save(); e.advanceRoutes(8); await route.done;
    await e.restore(npcSave); const npc = e.map.eventById(1);
    assert.equal(displayPosition(npc).x, 15.5); e.advanceRoutes(8); assert.equal(displayPosition(npc).x, 16);
    assert.equal(e.movement.jobs.size, 0, 'route tiếp tục đúng tiến độ sau save');
    e.map.locateEvent(1, 15, 10);
    route = e.movement.start(npc, { list: [{ code: 14, parameters: [2, -1] }, { code: 0 }] });
    assert.deepEqual(displayPosition(npc), { x: 15, y: 10, lift: 0 }); e.advanceRoutes(8);
    assert.deepEqual(displayPosition(npc), { x: 16, y: 9.5, lift: 32 }, 'jump nội suy vị trí và đỉnh parabol gốc');
    const jumpSave = e.save(); e.advanceRoutes(8); await route.done; await e.restore(jumpSave);
    assert.deepEqual(displayPosition(e.map.eventById(1)), { x: 16, y: 9.5, lift: 32 }); e.advanceRoutes(8);
    assert.deepEqual(displayPosition(e.map.eventById(1)), { x: 17, y: 9, lift: 0 });
    e.state.through = true; e.move(6); e.advanceRoutes(2); await e.loadMap(2, { x: 6, y: 6, direction: 2 });
    assert.deepEqual(position(), { x: 6, y: 6, lift: 0 }); assert.equal(e.state.moveFrames, 0);
    assert.ok(e.state.followers().every(entry => entry.x === 6 && !entry.motion), 'chuyển map dọn nội suy của cả đội');
    e.state.through = false; e.move(6); e.advanceRoutes(4); e.state.x = 2;
    assert.equal(position().x, 2, 'tọa độ bị script thay không giữ đường trượt cũ'); e.advanceRoutes(100);
    const chasing = e.map.eventById(1); chasing.chaseRange = 30; chasing.seePlayer = false;
    e.autonomousEnabled = true; e.advanceRoutes(1);
    assert.ok(chasing.motion, 'AI dùng chung nội suy với route');
    const start = displayPosition(chasing); e.advanceRoutes(8); const mid = displayPosition(chasing);
    assert.ok(mid.x !== start.x || mid.y !== start.y);
    console.log('ĐẠT: nội suy bước/chạy/camera/follower/guest, va chạm/203/chuyển map, NPC/AI/jump, tọa độ màn hình, pause và save giữa chuyển động.');
})().catch(error => { console.error(error); process.exitCode = 1; });

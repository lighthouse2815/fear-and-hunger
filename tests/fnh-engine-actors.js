execute(129, [2, 1, false]);
execute(129, [1, 1, false]);
assert.equal(scene.partyIds().length, 0, 'Cho phép tổ đội trống trong kịch bản');
assert.equal(scene.eventCondition([4, 1, 0]), false);
assert.equal(scene.eventActorTargets(0, 0).length, 0);
execute(129, [2, 0, false]);
assert.equal(scene.game.player.id, 2);
assert.equal(scene.game.player.inventory[0].amount, 3);
assert.equal(scene.eventDataOperand(6, 5), 0);
console.log('ĐẠT: thêm/bớt tổ đội, đổi trưởng nhóm, túi đồ chung, actor toàn đội và trang event.');
